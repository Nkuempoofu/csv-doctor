/**
 * Multilingual word dictionary for near-duplicate spell-correction.
 *
 * Covers ~9 000 words across English (default) + Spanish, French, Portuguese,
 * German, and Swahili:
 *   • The ~2 000 most common English words
 *   • All world countries (each word in multi-word names, in all supported languages)
 *   • Major cities / geographic terms
 *   • Business / professional vocabulary in all supported languages
 *   • Common proper nouns
 *
 * Usage:
 *   spellingScore("South Africa")  → 1.0  (both words are known)
 *   spellingScore("Soth Africa")   → 0.5  ("Soth" is unknown)
 *   spellingScore("Finance")       → 1.0
 *   spellingScore("Finanace")      → 0.0
 *   spellingScore("Finanzas")      → 1.0  (Spanish)
 *   spellingScore("Finances")      → 1.0  (French)
 *   spellingScore("Finanzen")      → 1.0  (German)
 */

/* ── helpers ─────────────────────────────────────────────────────────────── */

/** True when `word` is a recognised English word (case-insensitive). */
export function isKnownWord(word: string): boolean {
  return WORDS.has(word.toLowerCase().replace(/[^a-z]/g, ''));
}

/**
 * Fraction of alphabetic tokens in `value` that are known English words.
 * Returns 0.5 for purely numeric / symbolic values so they are treated as
 * neutral and fall back to the frequency tie-break.
 */
export function spellingScore(value: string): number {
  const tokens = value
    .trim()
    .split(/[\s\-_/,;]+/)
    .map(t => t.replace(/[^a-zA-Z]/g, ''))
    .filter(Boolean);
  if (tokens.length === 0) return 0.5;
  const hits = tokens.filter(t => isKnownWord(t)).length;
  return hits / tokens.length;
}

